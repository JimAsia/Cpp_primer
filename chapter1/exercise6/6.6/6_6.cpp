#include <iostream>


// 函数定义
// val: 形参
void counter(int val) 
{
    // local_var: 普通局部变量（自动变量）
    // 每次调用函数时，它都会被重新创建并初始化为 0
    int local_var = 0; 

    // static_var: 局部静态变量
    // 只有第一次调用时会初始化为 0。
    // 之后再次调用时，这行代码会被跳过，它会保留上一次的值。
    static int static_var = 0; 

    // 执行逻辑
    local_var++;      // 局部变量自增
    static_var++;     // 静态变量自增

    std::cout << "传入参数(形参): " << val << " | ";
    std::cout << "局部变量: " << local_var << " | ";
    std::cout << "静态变量: " << static_var << std::endl;
}

int main() {
    std::cout << "--- 第1次调用 ---" << std::endl;
    counter(10); // 传入实参 10

    std::cout << "--- 第2次调用 ---" << std::endl;
    counter(20); // 传入实参 20

    std::cout << "--- 第3次调用 ---" << std::endl;
    counter(30); // 传入实参 30

    return 0;
}
/*

形参、局部变量、局部静态变量的区别
（1）形参（形式参数）
定义：在定义函数时，括号中声明的变量。
作用域：仅限于函数内部，属于局部变量的一种。
生命周期：在函数被调用时创建，函数调用结束时销毁。
存储方式：通常存储在栈（自动变量）中。
初始化：由调用者传入实参进行初始化。
（2）局部变量（自动变量）
定义：在函数内部或复合语句（如 {} 块）中定义的变量（未加 static 修饰）。
作用域：仅限于定义它的函数或代码块内部。
生命周期：进入作用域时创建，离开作用域时销毁。
存储方式：存储在栈中（自动存储）。
初始化：如果不显式初始化，其值是未定义的（随机值）。
（3）局部静态变量（static 局部变量）
定义：在函数内部使用 static 关键字修饰的变量。
作用域：仍然仅限于定义它的函数内部（局部作用域）。
生命周期：程序整个运行期间都存在（静态存储），只在第一次执行到定义处时初始化一次。
存储方式：存储在静态存储区（全局数据区）。
初始化：默认初始化为 0（数值型）或空（指针型），且只初始化一次。
*/