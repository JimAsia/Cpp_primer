#include <iostream>
#include <limits> // 用于获取 int 的最大值

using namespace std;

int main() {
    // 1. 定义两个非常大的整数，模拟大数组的索引
    int beg = std::numeric_limits<int>::max() - 2; // 大约是 21亿 - 2
    int end = std::numeric_limits<int>::max() - 1; // 大约是 21亿 - 1

    // 在数学上，这两个数的平均值应该是 21亿 - 1.5，向下取整为 21亿 - 2
    // 但我们来看看计算机是怎么计算的

    // ==========================================
    // ❌ 错误写法：mid = (beg + end) / 2;
    // ==========================================
    int mid_error = (beg + end) / 2; 

    // ==========================================
    // ✅ 正确写法：mid = beg + (end - beg) / 2;
    // ==========================================
    int mid_correct = beg + (end - beg) / 2;

    // 打印结果
    cout << "beg 的值: " << beg << endl;
    cout << "end 的值: " << end << endl;
    cout << "-----------------------------------" << endl;
    cout << "【错误写法】(beg + end) / 2 的结果: " << mid_error << " (发生了整数溢出，变成了负数！)" << endl;
    cout << "【正确写法】beg + (end - beg) / 2 的结果: " << mid_correct << " (安全且正确)" << endl;

    return 0;
}


/* 错误写法的结局：beg 和 end 都是 20 亿左右的超大正整数，当它们相加时，数值超出了 int 能容纳的最大范围（约 21.4 亿）。
在计算机底层，这会导致符号位被挤占，原本的正数直接变成了一个负数（通常会变成 -2）。


正确写法的结局：end - beg 的结果仅仅是 1，完全在 int 的安全范围内。(end - beg) / 2 得到 0，最后 beg + 0 依然安全地保留了原来的超大整数。


0 代表正数（+）
1 代表负数（-）
*/