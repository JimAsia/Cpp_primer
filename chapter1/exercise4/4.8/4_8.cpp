/*逻辑与（&&）和逻辑或（||）：短路求值（Short - Circuit Evaluation）
求值顺序：严格从左到右依次对运算对象求值。
短路特性：
对于 a && b：先计算 a 的值。如果 a 的结果为 false（或等价于 false，如 0、空指针等），则整个表达式的结果必然是 false，此时 b 不会被求值（因为无论 b 是什么，结果都不会改变）。只有当 a 为 true 时，才会继续计算 b 的值。
对于 a || b：先计算 a 的值。如果 a 的结果为 true（或等价于 true，如非零值、非空指针等），则整个表达式的结果必然是 true，此时 b 不会被求值。只有当 a 为 false 时，才会继续计算 b 的值。

相等性运算符（==、!=）：无短路，求值顺序未指定（但通常从左到右）
求值顺序：C++标准没有强制规定相等性运算符（==、!=）的运算对象求值顺序（即先算左边还是右边是“未指定行为”）。但在实际编译器实现中，通常按从左到右的顺序求值（但这不是标准保证的）。
无短路特性：无论左边的运算对象结果如何，右边的运算对象都会被求值（因为相等性判断需要同时知道左右两边的值才能确定结果）。
*/

/*
const char *cp = "Hello World";
if (cp && *cp)
在这个 if 语句中，条件 cp && *cp 的判断过程如下：
先判断指针 cp 是否为空：cp 是一个非空指针，结果为真，继续判断右侧。
再判断 *cp（即首字符 'H'）是否为零字符：'H' 不是 '\0'，结果为真。
综合结果：整个条件为真，if 语句块内的代码会被执行。
这个表达式实际上是在做双重检查：
确保指针 cp 本身是有效的（非空）。
确保指针所指向的字符不是字符串结束符（即字符串非空）。
*/

