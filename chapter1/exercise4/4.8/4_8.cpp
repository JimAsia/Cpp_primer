/*
i != j < k 就是 i != (j < k)
1. 优先级规则
在 C++ 运算符中，关系运算符（如 <, >, <=, >=）的优先级要高于 相等性运算符（如 ==, !=）。
2. 表达式的执行步骤
先计算括号内部分：首先计算 j < k。
如果 j 小于 k，j < k 的结果为 true（在布尔运算中，true 会被提升为整数 1）。
如果 j 不小于 k，j < k 的结果为 false（在布尔运算中，false 会被提升为整数 0）。
再计算不等号部分：将 i 的值与第一步的结果（1 或 0）进行比较，判断 i 是否不等于这个值。

*/
