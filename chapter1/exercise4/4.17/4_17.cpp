/*
核心区别：求值与返回
这是两者在逻辑上最根本的区别，决定了它们在表达式中的行为。
前置递增 (++i)：先加后用
过程：先将变量的值加 1，然后返回加 1 后的变量本身（引用）。
语义：“增加我，然后使用增加后的结果”。
后置递增 (i++)：先用后加
过程：先保存变量当前的旧值，然后将变量的值加 1，最后返回保存的旧值。
语义：“使用当前的结果，然后再增加我”。

性能与底层实现（C++ 特有重点）
在 C++ 中，对于内置类型（如 int, double），现代编译器通常会优化掉两者的性能差异。但是，对于自定义类型（如类对象、迭代器），区别非常大：
前置递增 (++i)：
直接修改对象并返回引用。
效率高，没有额外的内存开销。
后置递增 (i++)：
为了返回“旧值”，必须在内部创建一个临时对象（副本）来保存修改前的状态。
修改原对象后，返回那个临时副本。
效率低，涉及对象的构造和析构开销。
最佳实践： 在 C++ 的 for 循环或使用迭代器（Iterator）时，习惯上推荐使用前置递增 (++i)，以避免不必要的临时对象拷贝，养成高性能编程的习惯。
. 返回值属性（左值与右值）
前置递增 (++i)：返回的是左值（L-value），即变量本身的引用。这意味着你可以对它继续赋值或取地址。
例如：++i = 10; 是合法的（虽然不推荐这样写）。
后置递增 (i++)：返回的是右值（R-value），即一个临时的旧值副本。
例如：i++ = 10; 是非法的（在 C++11 及以后标准中明确禁止对右值赋值）。
*/



#include <iostream>
#include <vector>

using std::cout;
using std::endl;
using std::cin;
using std::vector;

int main()
{
    // 4.18
    /*
    前置递增（++）和解引用（*）的优先级是相同的，结合方向是从右向左。因此，编译器实际执行的顺序是：
    先执行 *pbeg：解引用迭代器，获取当前 pbeg 指向的元素（此时是 v 的第一个元素）。
    再执行 ++：将这个元素自身的值进行自增（比如第一个元素的值从 1 变成了 2）。
    输出结果。
    在整个过程中，迭代器 pbeg 自身从未发生移动！ 它永远指向 vector 的第一个元素。
    */
    vector<int> v = {1, 2, 3, 4, 5};
    auto pbeg = v.begin();
    while (pbeg != v.end() && *pbeg >= 0)
        cout << ++*pbeg << endl;   // 后置递增优先级高于前置递增 （后置 ++：优先级 高于 解引用 *）   （前缀 ++：优先级 等于 解引用 *）
    // 4.19
    /*
    (a) ptr != 0 && *ptr++
    含义解析：
    由于 != 和 * 的优先级高于 &&，且后置 ++ 优先级高于解引用 *，所以编译器实际解析为 (ptr != 0) && (*(ptr++))。
    逻辑含义是：先判断指针 ptr 是否不为空（ptr != 0）。如果是空指针，直接结束（短路求值，不执行右边）；如果不为空，则解引用获取 ptr 当前指向的整数值，并将指针 ptr 移动到下一个位置。
    是否正确：正确。
    (b) ival++ && ival
    含义解析：
    后置 ++ 优先级高于 &&，所以编译器解析为 (ival++) && ival。
    逻辑含义是：先返回 ival 的原始值用于左侧的逻辑判断，然后 ival 自身的值加 1；接着判断加 1 后的 ival 作为右侧条件。
    是否正确：正确。（int 类型的原始值和自增后的值都可以作为布尔逻辑判断条件）。
    (c) vec[ival++] <= vec[ival]
    含义解析：
    试图比较 vector 中索引为 ival 的元素和索引为 ival+1 的元素。
    是否正确：不正确（未定义行为）。
    为什么：<= 运算符的左右两个操作数，都同时读取和修改了 ival 的值（左边有 ival++ 修改，右边有 ival 读取）。
    在 C++ 中，如果在没有序列点（Sequence Point）的情况下，对一个对象同时进行读取和修改，属于未定义行为（Undefined Behavior）。
    编译器对左右操作数的求值顺序是没有规定的，程序可能会得出不可预知的结果。
    */
    return 0;
}