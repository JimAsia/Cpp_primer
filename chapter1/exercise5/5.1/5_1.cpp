/*
空语句是指仅由一个分号“;”构成的语句，它在程序执行时不产生任何操作或效果，即“什么也不做”。
空语句常用于以下场景：
作为循环体的占位符：当循环体暂时不需要执行任何操作时，可用空语句填充，避免语法错误。
用于延时或等待：在某些嵌入式或底层程序中，空语句可配合编译器优化或硬件特性实现简单延时。
作为控制语句的“空操作”分支：例如在switch语句中，某些case分支可能不需要执行任何操作，可用空语句表示“无操作”。
*/
// 5.2
/*
块（也称语句块）是指由若干条语句组成，并用一对花括号“{ }”括起来的复合语句。块在语法上被视为一个整体语句。
块常用于以下场景：
条件语句（if/else）中需要执行多条语句时：若if或else分支中需要执行多条语句，必须用块将它们包裹，否则只有第一条语句受条件控制。
循环语句（for/while/do-while）中需要执行多条语句时：循环体若包含多条语句，必须用块包裹。
函数体内：函数体本质上是一个块，用于组织函数内部的变量声明和语句。
局部作用域控制：块可以创建局部作用域，块内声明的变量仅在块内有效，有助于避免变量名冲突。
*/
#include<iostream>
int main() 
{
    int sum = 0;
    int i = 50;
    for (i; i <= 100; ++i)
        sum += i;
    std::cout << "The sum of 50 to 100 is " << sum << std::endl;
    return 0;
}